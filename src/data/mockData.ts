function formatLapTime(seconds: number): string {
  const mins = Math.floor(seconds / 60);
  const remSecs = (seconds % 60).toFixed(3);
  const paddedSecs = parseFloat(remSecs) < 10 ? `0${remSecs}` : remSecs;
  return `${mins}:${paddedSecs}`;
}

